def create_scatter_plot(true_values, predictions_dict, output_path, num_measurements):
    """
    Create a publication-quality scatter plot comparing predictions to true values
    
    Args:
        true_values: Array of true entanglement values
        predictions_dict: Dictionary mapping method names to prediction arrays
        output_path: Path to save the figure
        num_measurements: Number of measurements used
    """
    # Create figure with subplots
    fig, axes = plt.subplots(2, 3, figsize=(12, 8))
    axes = axes.flatten()
    
    # Only include methods that have predictions
    methods = [m for m in METHOD_STYLES.keys() if m in predictions_dict]
    
    # Perfect prediction line data
    min_val = min(true_values.min(), min(predictions_dict[m].min() for m in methods))
    max_val = max(true_values.max(), max(predictions_dict[m].max() for m in methods))
    perfect_line = np.array([min_val, max_val])
    
    # Add +/- 0.1 margin to the axis limits
    margin = 0.1
    plot_min = max(0, min_val - margin)
    plot_max = max_val + margin
    
    # Create scatter plots
    for i, method in enumerate(methods):
        if i < len(axes):
            ax = axes[i]
            
            # Get predictions for this method
            preds = predictions_dict[method]
            
            # Calculate metrics
            r2 = np.corrcoef(true_values, preds)[0, 1]**2
            rmse = np.sqrt(np.mean((true_values - preds)**2))
            method_style = METHOD_STYLES[method]
            
            # Create scatter plot
            ax.scatter(true_values, preds, 
                      s=15,  # Smaller point size 
                      color=method_style['color'],
                      alpha=0.6,
                      edgecolor='none')
            
            # Add perfect prediction line
            ax.plot(perfect_line, perfect_line, 'k--', linewidth=1.5, alpha=0.7)
            
            # Add +/- 0.1 error bands
            ax.fill_between(perfect_line, perfect_line - 0.1, perfect_line + 0.1, 
                           color='red', alpha=0.1)
            
            # Add metrics as text annotation
            ax.text(0.05, 0.95, f"{method_style['nice_name']}\n$R^2 = {r2:.3f}$\nRMSE = {rmse:.3f}", 
                   transform=ax.transAxes, fontsize=9, verticalalignment='top',
                   bbox=dict(boxstyle='round,pad=0.3', facecolor='white', alpha=0.8))
            
            # Set consistent limits and labels
            ax.set_xlim(plot_min, plot_max)
            ax.set_ylim(plot_min, plot_max)
            ax.set_xlabel("True Entanglement")
            ax.set_ylabel("Predicted Entanglement")
            
            # Add simple grid
            ax.grid(True, linestyle='--', alpha=0.3)
    
    # Hide unused subplots
    for i in range(len(methods), len(axes)):
        axes[i].axis('off')
            
    # Add super title
    fig.suptitle(f"Prediction Performance with {num_measurements} Measurements", fontsize=14)
    
    # Ensure proper layout
    plt.tight_layout(rect=[0, 0, 1, 0.95])
    
    # Save figure
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Created scatter plot: {output_path}")
    plt.close()

def create_error_distribution_plot(true_values, predictions_dict, output_path, num_measurements):
    """
    Create a publication-quality error distribution plot
    
    Args:
        true_values: Array of true entanglement values
        predictions_dict: Dictionary mapping method names to prediction arrays
        output_path: Path to save the figure
        num_measurements: Number of measurements used
    """
    # Create figure
    fig, ax = plt.subplots(figsize=(10, 6))
    
    # Only include methods that have predictions
    methods = [m for m in METHOD_STYLES.keys() if m in predictions_dict]
    
    # Calculate errors for each method
    error_data = []
    method_labels = []
    
    for method in methods:
        # Get predictions for this method
        preds = predictions_dict[method]
        
        # Calculate absolute error
        errors = preds - true_values
        error_data.append(errors)
        method_labels.append(METHOD_STYLES[method]['nice_name'])
    
    # Create violin plot
    vp = ax.violinplot(error_data, showmeans=True, showmedians=True)
    
    # Color the violins according to our color scheme
    for i, pc in enumerate(vp['bodies']):
        method = methods[i]
        pc.set_facecolor(METHOD_STYLES[method]['color'])
        pc.set_edgecolor('black')
        pc.set_alpha(0.7)
    
    # Add zero line
    ax.axhline(y=0, color='r', linestyle='-', alpha=0.3)
    
    # Set x-axis ticks with method names
    ax.set_xticks(range(1, len(method_labels) + 1))
    ax.set_xticklabels(method_labels, rotation=30, ha='right', fontsize=9)
    
    # Add labels and title
    ax.set_ylabel('Prediction Error (Predicted - True)', fontsize=12)
    ax.set_title(f'Error Distribution by Method ({num_measurements} Measurements)', 
                 fontsize=14)
    
    # Add statistics text
    stats_text = "Method   Mean ± Std   Median\n" + "-" * 35 + "\n"
    
    for i, method in enumerate(methods):
        errors = error_data[i]
        mean = np.mean(errors)
        std = np.std(errors)
        median = np.median(errors)
        
        stats_text += f"{method_labels[i].split()[0]:8s} {mean:.3f} ± {std:.3f}  {median:.3f}\n"
    
    # Add text box with statistics
    props = dict(boxstyle='round', facecolor='white', alpha=0.8)
    ax.text(0.5, -0.25, stats_text, transform=ax.transAxes, fontsize=8,
           verticalalignment='top', horizontalalignment='center',
           family='monospace', bbox=props)
    
    # Ensure proper layout
    plt.tight_layout(rect=[0, 0.05, 1, 0.98])
    plt.subplots_adjust(bottom=0.25)
    
    # Save figure
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Created error distribution plot: {output_path}")
    plt.close()

def create_summary_plots(data_dir, output_dir):
    """
    Create summary plots from benchmark results
    """
    # Check for benchmark results
    benchmark_file = os.path.join(data_dir, 'benchmark_results.csv')
    if not os.path.exists(benchmark_file):
        print(f"Benchmark results not found at {benchmark_file}")
        return
    
    print(f"Creating summary plots from benchmark results...")
    df = pd.read_csv(benchmark_file)
    
    # 1. MSE vs Number of Measurements
    plt.figure(figsize=(12, 8))
    for method in df['method'].unique():
        method_data = df[df['method'] == method]
        plt.plot(
            method_data['measurements'], 
            method_data['mse'], 
            marker=METHOD_STYLES[method]['marker'],
            linestyle=METHOD_STYLES[method]['linestyle'],
            color=METHOD_STYLES[method]['color'],
            label=METHOD_STYLES[method]['nice_name'],
            linewidth=2,
            markersize=10
        )
    
    plt.xlabel('Number of Measurements', fontsize=14)
    plt.ylabel('Mean Squared Error', fontsize=14)
    plt.title('MSE vs Number of Measurements Comparison', fontsize=16)
    plt.grid(alpha=0.3)
    plt.xscale('log')
    plt.yscale('log')
    plt.legend()
    plt.tight_layout()
    
    mse_plot_file = os.path.join(output_dir, 'mse_vs_measurements_comparison.png')
    plt.savefig(mse_plot_file, dpi=300)
    print(f"MSE comparison plot saved to {mse_plot_file}")
    plt.close()
    
    # 2. Time vs Number of Measurements
    plt.figure(figsize=(12, 8))
    for method in df['method'].unique():
        method_data = df[df['method'] == method]
        plt.plot(
            method_data['measurements'], 
            method_data['time'], 
            marker=METHOD_STYLES[method]['marker'],
            linestyle=METHOD_STYLES[method]['linestyle'],
            color=METHOD_STYLES[method]['color'],
            label=METHOD_STYLES[method]['nice_name'],
            linewidth=2,
            markersize=10
        )
    
    plt.xlabel('Number of Measurements', fontsize=14)
    plt.ylabel('Computation Time (seconds)', fontsize=14)
    plt.title('Computation Time vs Number of Measurements', fontsize=16)
    plt.grid(alpha=0.3)
    plt.xscale('log')
    plt.yscale('log')
    plt.legend()
    plt.tight_layout()
    
    time_plot_file = os.path.join(output_dir, 'time_vs_measurements_comparison.png')
    plt.savefig(time_plot_file, dpi=300)
    print(f"Time comparison plot saved to {time_plot_file}")
    plt.close()
    
    # 3. Efficiency Plot (MSE vs Time)
    plt.figure(figsize=(12, 8))
    
    # Define markers for different measurement counts
    measurement_markers = {
        10: 'o',
        20: 's',
        50: '^',
        100: 'D',
        250: 'P',
        400: '*'
    }
    
    for method in df['method'].unique():
        method_data = df[df['method'] == method]
        
        for _, row in method_data.iterrows():
            meas = row['measurements']
            mse = row['mse']
            comp_time = row['time']
            
            marker = measurement_markers.get(meas, 'o')
            
            # Plot point
            plt.scatter(
                comp_time,
                mse,
                s=100,
                marker=marker,
                color=METHOD_STYLES[method]['color'],
                edgecolors='white',
                label=f"{METHOD_STYLES[method]['nice_name']} - {meas} meas." if meas == method_data['measurements'].iloc[0] else ""
            )
            
        # Connect points for this method
        plt.plot(
            method_data['time'], 
            method_data['mse'], 
            linestyle='--',
            alpha=0.5,
            color=METHOD_STYLES[method]['color']
        )
    
    plt.xlabel('Computation Time (seconds)', fontsize=14)
    plt.ylabel('Mean Squared Error', fontsize=14)
    plt.title('Efficiency Frontier: Error vs Computation Time', fontsize=16)
    plt.grid(alpha=0.3)
    plt.xscale('log')
    plt.yscale('log')
    
    # Add "better" region annotation
    plt.annotate('Better →', xy=(0.02, 0.02), xycoords='axes fraction', 
               fontsize=12, fontweight='bold', color='green',
               bbox=dict(boxstyle='round,pad=0.3', fc='white', ec='gray', alpha=0.8))
    
    # Remove duplicate labels
    handles, labels = plt.gca().get_legend_handles_labels()
    by_label = dict(zip(labels, handles))
    plt.legend(by_label.values(), by_label.keys(), loc='best')
    
    plt.tight_layout()
    
    efficiency_plot_file = os.path.join(output_dir, 'efficiency_frontier.png')
    plt.savefig(efficiency_plot_file, dpi=300)
    print(f"Efficiency frontier plot saved to {efficiency_plot_file}")
    plt.close()

def plot_predictions(data_dir="prediction_outputs/benchmark_data", output_dir=None):
    """
    Create plots from prediction CSV files
    
    Args:
        data_dir: Directory containing prediction CSV files
        output_dir: Directory to save plot files (default: derived from data_dir)
    """
    if output_dir is None:
        # Create two output directories - one for scatter plots and one for summary plots
        scatter_dir = os.path.join(os.path.dirname(data_dir), "scatter_plots")
        summary_dir = os.path.join(os.path.dirname(data_dir), "comparison_plots")
    else:
        scatter_dir = os.path.join(output_dir, "scatter_plots")
        summary_dir = os.path.join(output_dir, "comparison_plots")
    
    os.makedirs(scatter_dir, exist_ok=True)
    os.makedirs(summary_dir, exist_ok=True)
    
    print(f"Scatter plots will be saved to: {scatter_dir}")
    print(f"Summary plots will be saved to: {summary_dir}")
    
    # Create summary plots from benchmark results
    create_summary_plots(data_dir, summary_dir)
    
    # Find all prediction CSV files
    prediction_files = []
    for file in os.listdir(data_dir):
        if file.startswith('predictions_') and file.endswith('.csv'):
            try:
                meas = int(file.replace('predictions_', '').replace('.csv', ''))
                prediction_files.append((meas, os.path.join(data_dir, file)))
            except ValueError:
                continue
    
    # Sort by measurement count
    prediction_files.sort()
    
    if not prediction_files:
        print(f"No prediction files found in {data_dir}")
        return
    
    print(f"Found {len(prediction_files)} prediction files")
    
    # Create plots for each measurement count
    for meas, file_path in prediction_files:
        print(f"Processing predictions for {meas} measurements...")
        try:
            # Load data
            df = pd.read_csv(file_path)
            
            if 'true_values' not in df.columns:
                print(f"Error: 'true_values' column not found in {file_path}")
                continue
            
            # Extract true values and predictions
            true_values = df['true_values'].values
            predictions_dict = {}
            
            for col in df.columns:
                if col != 'true_values':
                    method = col.replace('_pred', '').lower()
                    predictions_dict[method] = df[col].values
            
            # Create scatter plot
            scatter_path = os.path.join(scatter_dir, f'scatter_plot_{meas}.png')
            create_scatter_plot(true_values, predictions_dict, scatter_path, meas)
            
            # Create error distribution plot
            error_path = os.path.join(scatter_dir, f'error_distribution_{meas}.png')
            create_error_distribution_plot(true_values, predictions_dict, error_path, meas)
            
        except Exception as e:
            print(f"Error processing {file_path}: {e}")
    
    print(f"All plots have been saved to {scatter_dir} and {summary_dir}")

def main():
    """Simple script entry point with defaults"""
    data_dir = "prediction_outputs/benchmark_data"
    
    # Check if the default directory exists
    if not os.path.exists(data_dir):
        print(f"Default data directory '{data_dir}' not found.")
        data_dir = input("Enter the path to your data directory: ")
        if not os.path.exists(data_dir):
            print(f"Error: Directory '{data_dir}' does not exist.")
            return 1
    
    try:
        print(f"Creating plots from prediction data in {data_dir}...")
        plot_predictions(data_dir)
        print("Plot creation completed successfully!")
    except Exception as e:
        print(f"Error: {e}")
        import traceback
        traceback.print_exc()
        return 1
    
    return 0

if __name__ == "__main__":
    sys.exit(main())
